fn visit_strings(value: &Value, f: &mut impl FnMut(&str)) {
    match value {
        Value::String(text) => f(text),
        Value::Mapping(fields) => {
            for (_, v) in fields {
                visit_strings(v, f);
            }
        }
        Value::Sequence(items) => {
            for v in items {
                visit_strings(v, f);
            }
        }
        _ => (),
    }
}

#[test]
fn actual_steps_have_no_dangling_references_or_command_environment_bridge() {
    for file in workflow_definitions::FILES {
        for document in sources(file) {
            assert_eq!(document["permissions"]["contents"], "read");
            for (job_name, job) in document["jobs"].as_mapping().unwrap() {
                let Some(sequence) = job["steps"].as_sequence() else {
                    continue;
                };
                let ids = sequence
                    .iter()
                    .filter_map(|step| step["id"].as_str())
                    .collect::<BTreeSet<_>>();
                assert_eq!(
                    ids.len(),
                    sequence.iter().filter(|s| s["id"].is_string()).count(),
                    "duplicate id: {file}/{job_name:?}"
                );
                visit_strings(job, &mut |text| {
                    for tail in text.split("steps.").skip(1) {
                        let reference = tail.split('.').next().unwrap();
                        assert!(
                            ids.contains(reference),
                            "{file}/{job_name:?}: dangling steps.{reference}"
                        );
                    }
                    assert!(!text.contains("toJSON(steps)") && !text.contains("CI_STEPS"));
                });
                for step in sequence {
                    if let Some(command) = step["run"].as_str() {
                        assert!(!command.contains("${{") && !command.contains('\n'));
                        assert!(!step["shell"].is_string());
                        if command.contains(" ci segment ") {
                            assert!(
                                step["continue-on-error"].is_null(),
                                "required work became optional"
                            );
                        }
                    }
                }
            }
        }
    }
}

#[test]
fn native_checkpoint_is_between_actual_compilation_and_execution() {
    for document in sources("ci.yml") {
        let sequence = steps(&document, "native");
        for windows in [false, true] {
            let marker = if windows {
                "memcordon-ci.exe ci segment "
            } else {
                "memcordon-ci ci segment "
            };
            let compile = sequence
                .iter()
                .position(|s| {
                    s["run"]
                        .as_str()
                        .is_some_and(|r| r.ends_with(&format!("{marker}native-compile")))
                })
                .unwrap();
            let execute = sequence
                .iter()
                .position(|s| {
                    s["run"]
                        .as_str()
                        .is_some_and(|r| r.ends_with(&format!("{marker}native-execute")))
                })
                .unwrap();
            let owner = sequence[compile]["id"].as_str().unwrap();
            assert!(sequence[compile + 1..execute].iter().any(|step| {
                step["uses"]
                    .as_str()
                    .is_some_and(|uses| uses.starts_with("actions/cache/save@"))
                    && step["if"].as_str().is_some_and(|condition| {
                        condition.contains(&format!(
                            "steps.{owner}.outputs.native-tests-complete-save == 'true'"
                        ))
                    })
            }));
            assert!(sequence[compile + 1..execute].iter().any(|step| {
                step["if"].as_str().is_some_and(|condition| {
                    condition.contains(&format!(
                        "steps.{owner}.outputs.native-tests-partial-save == 'true'"
                    ))
                })
            }));
        }
    }
}

#[test]
fn publishers_and_rehearsal_never_restore_cached_executables() {
    for document in sources("release.yml") {
        for name in [
            "publish",
            "recovery-publish",
            "rehearse",
            "recovery-rehearse",
        ] {
            let sequence = steps(&document, name);
            assert!(sequence.iter().all(|step| {
                !step["uses"]
                    .as_str()
                    .is_some_and(|uses| uses.starts_with("actions/cache/"))
            }));
            assert!(sequence.iter().all(|step| {
                !step["run"].as_str().is_some_and(|run| {
                    run.contains("ci-runtime") || run.contains("driver-bootstrap")
                })
            }));
        }
        assert!(
            document["jobs"]["publish"]["needs"]
                .as_sequence()
                .unwrap()
                .iter()
                .any(|need| need == "rehearse")
        );
        assert!(
            document["jobs"]["recovery-publish"]["needs"]
                .as_sequence()
                .unwrap()
                .iter()
                .any(|need| need == "recovery-rehearse")
        );
        let select = steps(&document, "select");
        assert!(
            select
                .iter()
                .any(|s| s["run"]
                    .as_str()
                    .is_some_and(|run| run.contains(
                        "cargo build --locked --release --target-dir target/ci-driver-cold"
                    ) && run.ends_with("--bin memcordon-ci"))),
            "publication tool producer must actually compile current source"
        );
    }
}

#[test]
fn actual_cache_adapter_mutations_are_rejected() {
    let root = root();
    let configuration = config::policy(&root).unwrap();
    for file in workflow_definitions::FILES {
        let relative = Path::new(".github/workflows").join(file);
        let document = workflow_definitions::definition(file).unwrap();
        policy::validate_workflow_bytes(
            &root,
            &relative,
            serde_yaml::to_string(&document).unwrap().as_bytes(),
            &configuration,
        )
        .unwrap();
        let (job_name, index) = document["jobs"]
            .as_mapping()
            .unwrap()
            .iter()
            .find_map(|(name, job)| {
                if !job["steps"].as_sequence()?.iter().any(|s| {
                    s["run"]
                        .as_str()
                        .is_some_and(|r| r.contains(" ci segment "))
                }) {
                    return None;
                }
                job["steps"]
                    .as_sequence()?
                    .iter()
                    .position(|s| {
                        s["uses"]
                            .as_str()
                            .is_some_and(|u| u.starts_with("actions/cache/save@"))
                            && s["if"]
                                .as_str()
                                .is_some_and(|c| c.contains("-complete-save"))
                    })
                    .map(|index| (name.as_str().unwrap().to_owned(), index))
            })
            .unwrap();
        for mutation in [
            "success",
            "missing-always",
            "partial-as-complete",
            "environment",
            "required-optional",
            "early-boundary",
        ] {
            let mut changed = document.clone();
            let sequence = changed["jobs"][&job_name]["steps"]
                .as_sequence_mut()
                .unwrap();
            match mutation {
                "success" => {
                    sequence[index]["if"] =
                        format!("success() && {}", sequence[index]["if"].as_str().unwrap()).into()
                }
                "missing-always" => {
                    sequence[index]["if"] = sequence[index]["if"]
                        .as_str()
                        .unwrap()
                        .strip_prefix("always() && ")
                        .unwrap()
                        .into()
                }
                "partial-as-complete" => {
                    sequence[index]["with"]["key"] = sequence[index]["with"]["key"]
                        .as_str()
                        .unwrap()
                        .replace("-complete-key", "-partial-key")
                        .into()
                }
                "environment" => {
                    sequence[index]["env"] =
                        serde_yaml::from_str("CI_STEPS: '${{ toJSON(steps) }}'").unwrap();
                }
                "required-optional" => {
                    let work = sequence
                        .iter_mut()
                        .find(|s| {
                            s["run"]
                                .as_str()
                                .is_some_and(|r| r.contains(" ci segment "))
                        })
                        .unwrap();
                    work["continue-on-error"] = true.into();
                }
                "early-boundary" => {
                    let save = sequence.remove(index);
                    sequence.push(save);
                }
                _ => unreachable!(),
            }
            let error = workflow_definitions::validate_semantics(&changed)
                .unwrap_err()
                .to_string();
            let expected = match mutation {
                "success" | "missing-always" | "partial-as-complete" => "cache save adapter",
                "environment" => "environment bridge",
                "required-optional" => "required work became optional",
                "early-boundary" => "early retention boundary",
                _ => unreachable!(),
            };
            assert!(
                error.contains(expected)
                    || (mutation == "partial-as-complete"
                        && error.contains("cache slot does not belong to its finite recipe")),
                "{file}/{mutation}: wrong semantic reason: {error}"
            );
        }
    }
}
