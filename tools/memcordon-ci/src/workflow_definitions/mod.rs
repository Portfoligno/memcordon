fn text(value: &str) -> Value {
    Value::String(value.to_owned())
}
fn number(value: &str) -> Value {
    serde_yaml::from_str(value).expect("source-defined number")
}
fn literal(value: LiteralRun) -> Value {
    text(value.command())
}

pub const FILES: [&str; 4] = [
    "ci.yml",
    "deep-ci.yml",
    "backend-certification.yml",
    "release.yml",
];

pub fn validate_semantics(document: &Value) -> Result<()> {
    semantics::validate(document)
}

pub fn validate_public_source_model(root: &Path) -> Result<()> {
    source_seed::validate_source_model(root)
}

pub(crate) fn original(name: &str) -> Option<Value> {
    Some(match name {
        "ci.yml" => ci::definition(),
        "deep-ci.yml" => deep::definition(),
        "backend-certification.yml" => backend::definition(),
        "release.yml" => release::definition(),
        _ => return None,
    })
}

pub fn definition(name: &str) -> Result<Value> {
    let mut value =
        original(name).ok_or_else(|| CiError::Message("unknown workflow definition".into()))?;
    adapters::apply(&mut value, name)?;
    native_coverage::apply(&mut value, name)?;
    validate_references(&value)?;
    validate_semantics(&value)?;
    Ok(value)
}

fn validate_references(workflow: &Value) -> Result<()> {
    fn strings(value: &Value, values: &mut Vec<String>) {
        match value {
            Value::String(text) => values.push(text.clone()),
            Value::Mapping(fields) => {
                for (_, v) in fields {
                    strings(v, values);
                }
            }
            Value::Sequence(items) => {
                for v in items {
                    strings(v, values);
                }
            }
            _ => (),
        }
    }
    for (name, job) in workflow["jobs"].as_mapping().expect("source jobs") {
        let Some(steps) = job["steps"].as_sequence() else {
            continue;
        };
        let ids = steps
            .iter()
            .filter_map(|s| s["id"].as_str())
            .collect::<BTreeSet<_>>();
        if ids.len() != steps.iter().filter(|s| s["id"].is_string()).count() {
            return Err(CiError::Message(format!(
                "duplicate generated id in {name:?}"
            )));
        }
        let mut values = Vec::new();
        strings(job, &mut values);
        for value in values {
            for tail in value.split("steps.").skip(1) {
                let reference = tail.split('.').next().unwrap_or_default();
                if !ids.contains(reference) {
                    return Err(CiError::Message(format!(
                        "dangling generated steps.{reference} in {name:?}"
                    )));
                }
            }
        }
    }
    Ok(())
}

pub fn render(name: &str) -> Result<String> {
    let rendered = format!(
        "# Generated by memcordon-ci ci workflows --write.\n# Source: tools/memcordon-ci/src/workflow_definitions/\n{}",
        formatting::serialize(name, &definition(name)?)?
    );
    // Keep a conservative bound on the actual checked-in representation,
    // including presentation expansion and the generated header.
    const MAX_RENDERED_WORKFLOW_BYTES: usize = 500 * 1024;
    if rendered.len() > MAX_RENDERED_WORKFLOW_BYTES {
        return Err(CiError::Message(format!(
            "generated workflow {name} exceeds the {MAX_RENDERED_WORKFLOW_BYTES}-byte size budget: {} bytes",
            rendered.len()
        )));
    }
    Ok(rendered)
}

pub fn run(root: &Path, write: bool) -> Result<()> {
    for file in FILES {
        let expected = render(file)?;
        let path = root.join(".github/workflows").join(file);
        if write {
            fs::write(path, expected)?;
        } else {
            // Git may check these text files out with CRLF. Ignore only that
            // newline representation; all other generated content stays exact.
            if fs::read_to_string(path)?.replace("\r\n", "\n") != expected {
                return Err(CiError::Message(format!(
                    "generated workflow drift: {file}; run memcordon-ci ci workflows --write"
                )));
            }
        }
    }
    Ok(())
}

/// Keep independently maintained graph/credential checks during migration.
/// Only exact generated step adapters are projected. Actual events, jobs,
/// dependencies, permissions, matrices and outputs remain the validator input.
pub(crate) fn policy_projection(name: &str, actual: &Value) -> Result<Option<Mapping>> {
    let Some(original) = original(name) else {
        return Ok(None);
    };
    validate_semantics(actual)?;
    let expected = definition(name)?;
    let mut projected = actual
        .as_mapping()
        .ok_or_else(|| CiError::Message("workflow mapping absent".into()))?
        .clone();
    if name == "release.yml" {
        concurrency::project_native_coverage(&mut projected, &expected)?;
        release_fuzz::project(&mut projected, &expected, &original)?;
        host_preparation::project(&mut projected, &expected, &original)?;
    }
    if name == "backend-certification.yml" {
        backend_private::project(&mut projected, &expected, &original)?;
    }
    concurrency::project(&mut projected, &expected, &original, name)?;
    if let Some(jobs) = projected
        .get_mut(text("jobs"))
        .and_then(Value::as_mapping_mut)
    {
        jobs.remove(text("source-seed")); // Independently validated above; no legacy equivalent.
        for (job_name, job) in jobs.iter_mut() {
            if job["env"]["CARGO_HOME"].as_str() == Some(source_seed::CARGO_HOME_VALUE) {
                job.as_mapping_mut().expect("job map").remove(text("env"));
            }
            if name == "release.yml" && job_name.as_str() == Some("fuzz") {
                continue; // The complete actual fuzz phases were checked above.
            }
            if (name == "release.yml"
                && job_name
                    .as_str()
                    .is_some_and(host_preparation::projected_job))
                || (name == "backend-certification.yml"
                    && job_name.as_str() == Some("private-linux"))
            {
                continue; // Complete real jobs were compared before finite legacy projection.
            }
            if matches!(name, "ci.yml" | "release.yml")
                && matches!(
                    job_name.as_str(),
                    Some("quality" | "source-checks" | "supply-chain")
                )
            {
                continue; // Exact split topology was checked before projection.
            }
            let Some(baseline) = original["jobs"].get(job_name).and_then(Value::as_mapping) else {
                if let Some(expected_job) = expected["jobs"].get(job_name)
                    && job["steps"] != expected_job["steps"]
                {
                    return Err(CiError::Message(
                        "new workflow phase differs from its Rust step adapters".into(),
                    ));
                }
                continue;
            };
            let generated = &expected["jobs"][job_name]["steps"];
            let legacy = baseline.get(text("steps")).unwrap_or(&Value::Null);
            if generated == legacy {
                continue;
            }
            if job["steps"] != *generated {
                return Err(CiError::Message(format!(
                    "workflow differs from its Rust step adapters: {name}/{}",
                    job_name.as_str().unwrap_or("?")
                )));
            }
            job.as_mapping_mut()
                .ok_or_else(|| CiError::Message("job mapping absent".into()))?
                .insert(text("steps"), legacy.clone());
            if let Some(timeout) = baseline.get(text("timeout-minutes")) {
                job.as_mapping_mut()
                    .expect("job map")
                    .insert(text("timeout-minutes"), timeout.clone());
            }
        }
        if name == "deep-ci.yml" {
            jobs.remove(text("fuzz-setup"));
            if let Some(fuzz) = jobs.get_mut(text("fuzz")).and_then(Value::as_mapping_mut) {
                for field in ["needs", "if"] {
                    fuzz.insert(text(field), original["jobs"]["fuzz"][field].clone());
                }
            }
        }
    }
    Ok(Some(projected))
}

pub(crate) fn known_run(command: &str) -> bool {
    static COMMANDS: OnceLock<BTreeSet<String>> = OnceLock::new();
    fn collect(value: &Value, commands: &mut BTreeSet<String>) {
        match value {
            Value::Mapping(fields) => {
                for (key, value) in fields {
                    if key.as_str() == Some("run") {
                        commands.insert(value.as_str().expect("literal run").to_owned());
                    } else {
                        collect(value, commands);
                    }
                }
            }
            Value::Sequence(values) => {
                for value in values {
                    collect(value, commands);
                }
            }
            _ => (),
        }
    }
    COMMANDS
        .get_or_init(|| {
            let mut commands = BTreeSet::new();
            for name in FILES {
                collect(
                    &definition(name).expect("valid source-defined workflow"),
                    &mut commands,
                );
            }
            commands
        })
        .contains(command)
}

/// Validate migrated save forms independently of renderer equality. This check
/// intentionally has no aggregate job result, completion string, or step map.
pub(crate) fn validate_ready_save(step: &Mapping) -> Result<bool> {
    let Some(inputs) = step.get(text("with")).and_then(Value::as_mapping) else {
        return Ok(false);
    };
    let Some(key) = inputs.get(text("key")).and_then(Value::as_str) else {
        return Ok(false);
    };
    let Some(reference) = key
        .strip_prefix("${{ steps.")
        .and_then(|s| s.strip_suffix("-key }}"))
    else {
        return Ok(false);
    };
    let Some((owner, slot)) = reference.split_once(".outputs.") else {
        return Ok(false);
    };
    if !slot.ends_with("complete")
        && !slot.ends_with("partial")
        && !slot.ends_with("image")
        && !matches!(slot, "bootstrap" | "image" | "sysroot")
    {
        return Ok(false);
    }
    let ready = format!("always() && steps.{owner}.outputs.{slot}-save == 'true'");
    let probe = format!("{owner}-{slot}-probe");
    let expected = if slot.ends_with("partial") {
        ready
    } else {
        format!("{ready} && steps.{probe}.outputs.cache-hit != 'true'")
    };
    let expected_path = format!("${{{{ steps.{owner}.outputs.{slot}-path }}}}");
    if step.get(text("if")).and_then(Value::as_str) != Some(expected.as_str())
        || inputs.get(text("path")).and_then(Value::as_str) != Some(expected_path.as_str())
        || step.get(text("continue-on-error")).and_then(Value::as_bool) != Some(true)
        || step.get(text("timeout-minutes")).and_then(Value::as_u64) != Some(2)
    {
        return Err(CiError::Message(
            "invalid Rust-owned cache save adapter".into(),
        ));
    }
    Ok(true)
}
