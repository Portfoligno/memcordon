//! Rust authoring source for the four checked-in Actions workflows.
//! The current graph is authored once; no historical graph or projection is kept.
mod backend;
pub mod budget;
mod ci;
mod deep;
mod formatting;
mod release;
mod semantics;
mod source_seed;
mod workflow_budget;

use crate::{CiError, Result};
use serde_yaml::Value;
use std::{collections::BTreeSet, fs, path::Path, sync::OnceLock};

fn text(value: &str) -> Value {
    Value::String(value.to_owned())
}

pub const FILES: [&str; 4] = [
    "ci.yml",
    "deep-ci.yml",
    "backend-certification.yml",
    "release.yml",
];

pub fn validate_semantics(document: &Value) -> Result<()> {
    semantics::validate(document)
}
pub fn validate_public_source_model(root: &Path) -> Result<()> {
    source_seed::validate_source_model(root)
}

pub fn definition(name: &str) -> Result<Value> {
    let value = match name {
        "ci.yml" => ci::definition(),
        "deep-ci.yml" => deep::definition(),
        "backend-certification.yml" => backend::definition(),
        "release.yml" => release::definition(),
        _ => return Err(CiError::Message("unknown workflow definition".into())),
    };
    validate_semantics(&value)?;
    Ok(value)
}

pub fn render(name: &str) -> Result<String> {
    let rendered = format!(
        "# Generated by memcordon-ci ci workflows --write.\n# Source: tools/memcordon-ci/src/workflow_definitions/\n{}",
        formatting::serialize(name, &definition(name)?)?
    );
    if rendered.len() > 500 * 1024 {
        return Err(CiError::Message(
            "generated workflow exceeds size budget".into(),
        ));
    }
    Ok(rendered)
}

pub fn run(root: &Path, write: bool) -> Result<()> {
    for file in FILES {
        let expected = render(file)?;
        let path = root.join(".github/workflows").join(file);
        if write {
            fs::write(path, expected)?;
        } else if fs::read_to_string(path)?.replace("\r\n", "\n") != expected {
            return Err(CiError::Message(format!(
                "generated workflow drift: {file}; run memcordon-ci ci workflows --write"
            )));
        }
    }
    Ok(())
}

/// Validate the actual current graph, without projecting retired job definitions.
pub(crate) fn validate_current_model(name: &str, actual: &Value) -> Result<bool> {
    if !FILES.contains(&name) {
        return Ok(false);
    }
    validate_semantics(actual)?;
    if *actual != definition(name)? {
        return Err(CiError::Message(
            "workflow differs from current Rust authoring graph".into(),
        ));
    }
    Ok(true)
}

pub(crate) fn known_run(command: &str) -> bool {
    static COMMANDS: OnceLock<BTreeSet<String>> = OnceLock::new();
    fn collect(value: &Value, commands: &mut BTreeSet<String>) {
        match value {
            Value::Mapping(fields) => {
                for (key, value) in fields {
                    if key.as_str() == Some("run") {
                        commands.insert(value.as_str().expect("literal run").to_owned());
                    } else {
                        collect(value, commands);
                    }
                }
            }
            Value::Sequence(values) => {
                for value in values {
                    collect(value, commands);
                }
            }
            _ => (),
        }
    }
    COMMANDS
        .get_or_init(|| {
            let mut commands = BTreeSet::new();
            for name in FILES {
                collect(
                    &definition(name).expect("valid source-defined workflow"),
                    &mut commands,
                );
            }
            commands
        })
        .contains(command)
}
